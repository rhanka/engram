/** N1-N4: deterministic native projection of a parsed [ONT] value. */
export function buildOpenerpProfileV1(ont: { readonly entities: readonly { readonly entity: string }[]; readonly relations: readonly { readonly from: string; readonly field: string; readonly to: string }[] }): OntologyProfile {
  const node_types: Record<string, OntologyNodeType> = {};
  for (const e of ont.entities) node_types[e.entity] = {};
  const relation_types: Record<string, OntologyRelationType> = {};
  for (const r of ont.relations) relation_types[r.from + "." + r.field] = { source: r.from, target: r.to };
  return { id: "openerp", version: "1", default_language: "en", node_types, relation_types };
}

