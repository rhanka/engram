/** N4: closed field audit — every key in the pre-normalization value is native (\u00a72.9.0). */
export function auditOpenerpProfileFields(profile: Record<string, unknown>): string[] {
  const problems: string[] = [];
  for (const key of Object.keys(profile)) {
    if (!["id", "version", "default_language", "node_types", "relation_types"].includes(key)) problems.push("top:" + key);
  }
  for (const [id, value] of Object.entries((profile["node_types"] as Record<string, unknown>) ?? {})) {
    if (Object.keys((value as Record<string, unknown>) ?? {}).length !== 0) problems.push("node:" + id);
  }
  for (const [id, value] of Object.entries((profile["relation_types"] as Record<string, unknown>) ?? {})) {
    const keys = Object.keys((value as Record<string, unknown>) ?? {}).sort().join(",");
    if (keys !== "source,target") problems.push("relation:" + id);
  }
  return problems;
}

