// any §8 item is missing or if any carried sha256 drifts. Fixture bytes
// carried in this repository are stored verbatim under tests/fixtures;
// remote-only sources resolve with git show revision:path and are never
// re-read from a mutable path.
import type { Digest } from "./types.js";

export interface CorpusSource {
  readonly repo: string;
  readonly revision: string;
  readonly path: string;
}

export type CorpusKind =
  | "instance"
  | "frozen-fixture"
  | "producer-snapshot"
  | "native-source"
  | "matrix-source"
  | "derived-oracle"
  | "sealed-vector"
  | "bpmn-corpus"
  | "evidence";

export interface CorpusEntry {
  readonly id: string;
  readonly kind: CorpusKind;
  readonly source: CorpusSource;
  readonly sha256: Digest;
  /** Expected migration/validation/projection outcome taken from the spec. */
  readonly expectation: string;
}

const HEX64 = /^[0-9a-f]{64}$/;

function entry(
  id: string, kind: CorpusKind,
  repo: string, revision: string, path: string,
  sha256: Digest, expectation: string,
): CorpusEntry {
  if (!HEX64.test(sha256)) throw new Error(`corpus manifest: bad sha for ${id}`);
  return { id, kind, source: { repo, revision, path }, sha256, expectation };
}

