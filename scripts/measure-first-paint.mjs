#!/usr/bin/env node
/**
 * Measure the studio's FIRST-PAINT critical path, before vs after the storage
 * LOT 3 windowed loader.
 *
 * What "first paint" means here is taken straight from the client code, not
 * invented for the benchmark:
 *
 *   BEFORE — `sceneLoader.loadWorkspace()` resolves only after BOTH
 *     `fetchScene()` (scene.json) and `fetchGraph()` (graph.json) have settled,
 *     and `App.onMount` flips `loaded = true` only after that. So the bytes on
 *     the critical path are scene.json + graph.json, and the SPA parses them.
 *
 *   AFTER — `sceneLoader.loadWorkspaceWindowed()` probes the store window
 *     FIRST and paints it via `onFirstPaint` before `loadWorkspace()` is even
 *     called. So the bytes on the critical path are the window document alone.
 *
 * Both are measured the same way: over real HTTP from a local server, reading
 * the full body and then JSON.parse-ing it (the SPA does parse what it fetches).
 * The window is generated by the SAME `degree-top-n` algorithm the Postgres
 * adapter implements — top-N by degree, then the edges induced among them,
 * annotated with the layout's precomputed positions — so the payload measured
 * is the payload the route would serve.
 *
 * Usage:
 *   node --max-old-space-size=8192 scripts/measure-first-paint.mjs \
 *     --bundle <dir with graph.json + scene.json> [--limit 2000] [--runs 3]
 */
import { createReadStream, readFileSync, statSync } from "node:fs";
import { createServer } from "node:http";
import { join } from "node:path";

function parseArgs(argv) {
  const args = { limit: 2000, runs: 3 };
  for (let i = 2; i < argv.length; i += 1) {
    const flag = argv[i];
    if (flag === "--bundle") args.bundle = argv[++i];
    else if (flag === "--limit") args.limit = Number(argv[++i]);
    else if (flag === "--runs") args.runs = Number(argv[++i]);
  }
  if (!args.bundle) {
    console.error("error: --bundle <dir> is required (a dir with graph.json + scene.json)");
    process.exit(1);
  }
  return args;
}

const MB = 1024 * 1024;
const fmtBytes = (n) => `${(n / MB).toFixed(2)} MB`;
const fmtMs = (n) => `${n.toFixed(0)} ms`;

/**
 * Build a `degree-top-n` window, mirroring `postgres.graphWindow()`:
 *   1. top-N nodes ordered by (degree DESC, id ASC);
 *   2. the edges INDUCED among them (both endpoints inside the window);
 *   3. each node annotated with its precomputed layout position.
 * Positions come from scene.json, which is where the pinned layout lives — the
 * same values a `store push` bakes into `graph_positions`.
 */
function buildWindow(graph, scene, limit) {
  const links = graph.links ?? graph.edges ?? [];
  const degree = new Map();
  for (const edge of links) {
    degree.set(edge.source, (degree.get(edge.source) ?? 0) + 1);
    degree.set(edge.target, (degree.get(edge.target) ?? 0) + 1);
  }
  const positions = new Map();
  for (const node of scene?.nodes ?? []) {
    if (Number.isFinite(node.x) && Number.isFinite(node.y)) {
      positions.set(node.id, { x: node.x, y: node.y });
    }
  }
  const ranked = graph.nodes
    .map((node) => ({ node, degree: degree.get(node.id) ?? 0 }))
    .sort((a, b) => b.degree - a.degree || String(a.node.id).localeCompare(String(b.node.id)))
    .slice(0, limit);

  const ids = new Set(ranked.map((r) => r.node.id));
  const nodes = ranked.map(({ node, degree: d }) => {
    const out = { id: node.id, label: node.label ?? String(node.id), degree: d };
    const type = node.node_type ?? node.type;
    if (type) out.node_type = type;
    const pos = positions.get(node.id);
    if (pos) {
      out.x = pos.x;
      out.y = pos.y;
    }
    return out;
  });
  const edges = [];
  for (const edge of links) {
    if (ids.has(edge.source) && ids.has(edge.target)) {
      edges.push({
        source: edge.source,
        target: edge.target,
        relation: edge.relation ?? edge.relation_type ?? "RELATED_TO",
      });
    }
  }
  return { strategy: "degree-top-n", layout: "force", limit, nodes, edges };
}

/** Fetch a URL, read the FULL body, JSON.parse it. Returns bytes + timings. */
async function measureFetch(url) {
  const started = performance.now();
  const response = await fetch(url);
  const buffer = Buffer.from(await response.arrayBuffer());
  const transferredAt = performance.now();
  const value = JSON.parse(buffer.toString("utf-8"));
  const parsedAt = performance.now();
  return {
    bytes: buffer.length,
    transferMs: transferredAt - started,
    parseMs: parsedAt - transferredAt,
    totalMs: parsedAt - started,
    value,
  };
}

const args = parseArgs(process.argv);
const graphPath = join(args.bundle, "graph.json");
const scenePath = join(args.bundle, "scene.json");

console.log("=== studio first-paint measurement (storage LOT 3) ===");
console.log(`bundle: ${args.bundle}`);
console.log(`on disk: graph.json ${fmtBytes(statSync(graphPath).size)}, scene.json ${fmtBytes(statSync(scenePath).size)}`);

// --- Offline prep: build the window the route would serve. --------------------
const prepStart = performance.now();
const graph = JSON.parse(readFileSync(graphPath, "utf-8"));
const scene = JSON.parse(readFileSync(scenePath, "utf-8"));
const windowDoc = buildWindow(graph, scene, args.limit);
const windowBody = Buffer.from(`${JSON.stringify(windowDoc, null, 2)}\n`, "utf-8");
console.log(
  `corpus: ${graph.nodes.length} nodes / ${(graph.links ?? graph.edges ?? []).length} edges` +
    ` (window prep ${fmtMs(performance.now() - prepStart)}, offline — the store does this at push)`,
);
console.log(
  `window: ${windowDoc.nodes.length} nodes / ${windowDoc.edges.length} induced edges,` +
    ` ${windowDoc.nodes.filter((n) => n.x !== undefined).length} with precomputed positions`,
);
// Free the parsed corpus before measuring; it is prep, not first paint.
const corpusNodeCount = graph.nodes.length;

// --- Serve the artifacts over real HTTP. -------------------------------------
const server = createServer((request, response) => {
  if (request.url === "/api/ontology/window") {
    response.writeHead(200, {
      "content-type": "application/json; charset=utf-8",
      "content-length": windowBody.length,
      "cache-control": "no-store",
    });
    response.end(windowBody);
    return;
  }
  const file = request.url === "/api/ontology/scene.json" ? scenePath : graphPath;
  response.writeHead(200, {
    "content-type": "application/json; charset=utf-8",
    "content-length": statSync(file).size,
    "cache-control": "no-store",
  });
  createReadStream(file).pipe(response);
});
await new Promise((done) => server.listen(0, "127.0.0.1", done));
const base = `http://127.0.0.1:${server.address().port}`;

const median = (values) => {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
};

// --- BEFORE: scene.json + graph.json, both awaited before `loaded = true`. ----
const beforeRuns = [];
for (let run = 0; run < args.runs; run += 1) {
  const sceneRun = await measureFetch(`${base}/api/ontology/scene.json`);
  const graphRun = await measureFetch(`${base}/api/ontology/graph.json`);
  beforeRuns.push({
    bytes: sceneRun.bytes + graphRun.bytes,
    totalMs: sceneRun.totalMs + graphRun.totalMs,
  });
  global.gc?.();
}

// --- AFTER: the bounded window alone. ----------------------------------------
const afterRuns = [];
for (let run = 0; run < args.runs; run += 1) {
  const windowRun = await measureFetch(`${base}/api/ontology/window`);
  afterRuns.push({ bytes: windowRun.bytes, totalMs: windowRun.totalMs });
}

server.close();

const beforeBytes = beforeRuns[0].bytes;
const afterBytes = afterRuns[0].bytes;
const beforeMs = median(beforeRuns.map((r) => r.totalMs));
const afterMs = median(afterRuns.map((r) => r.totalMs));

console.log(`\n--- FIRST-PAINT CRITICAL PATH (median of ${args.runs} runs) ---`);
console.log(`BEFORE  scene.json + graph.json : ${fmtBytes(beforeBytes)}  ${fmtMs(beforeMs)}`);
console.log(`AFTER   window (limit=${args.limit})      : ${fmtBytes(afterBytes)}  ${fmtMs(afterMs)}`);
console.log(
  `\nreduction: ${(beforeBytes / afterBytes).toFixed(0)}x fewer bytes ` +
    `(${(100 - (afterBytes / beforeBytes) * 100).toFixed(2)}% less), ` +
    `${(beforeMs / afterMs).toFixed(0)}x faster to paintable data`,
);
console.log(
  `honest counters: ${windowDoc.nodes.length} of ${corpusNodeCount} nodes visible at first paint`,
);
